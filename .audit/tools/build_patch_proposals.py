"""Generate three unapplied, independently checkable patch proposals.

Only high-confidence actions are materialized. The complete decision queue stays
in todo.md; unresolved or measurement-gated C items are intentionally not
converted into speculative code.
"""

from __future__ import annotations

import argparse
import difflib
import re
from pathlib import Path


def replace_once(text: str, old: str, new: str, label: str) -> str:
    count = text.count(old)
    if count != 1:
        raise RuntimeError(f"{label}: expected one match, found {count}")
    return text.replace(old, new, 1)


def diff_text(path: str, before: str, after: str) -> str:
    return "".join(difflib.unified_diff(
        before.splitlines(keepends=True), after.splitlines(keepends=True),
        fromfile=f"a/{path}", tofile=f"b/{path}", n=3,
    ))


def add_file_diff(path: str, content: str) -> str:
    return "".join(difflib.unified_diff(
        [], content.splitlines(keepends=True), fromfile="/dev/null", tofile=f"b/{path}", n=3,
    ))


def load(snapshot: Path, path: str) -> str:
    return (snapshot / path).read_text(encoding="utf-8-sig")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("run_dir", type=Path)
    args = parser.parse_args()
    run = args.run_dir.resolve()
    snapshot = run / "snapshot"
    audit = run.parents[1]
    patch_dir = audit / "patches"
    patch_dir.mkdir(exist_ok=True)

    architecture = (audit / "ARCHITECTURE.md").read_text(encoding="utf-8")
    doc_content = (
        "# Architecture truth\n\n"
        "> Proposed documentation artifact generated by audit run `20260822T152307Z`.\n"
        "> Apply independently from comment or code changes.\n\n"
        + architecture.split("# AcneLLM — truth of architecture\n", 1)[-1]
    )
    a_patch = (
        "# Basket A: documentation only. Unapplied proposal.\n"
        "# Remaining A decisions are listed in .audit/todo.md.\n"
        + add_file_diff("docs/ARCHITECTURE_TRUTH.md", doc_content)
    )

    b_changes: dict[str, tuple[str, str]] = {}
    path = "src/acne_llm/utils/chunk_filter.py"
    before = load(snapshot, path)
    after = replace_once(
        before,
        "Shared chunk-quality filters used by both pipeline/hybrid.py and chat/runtime.py.",
        "Shared chunk-quality filters used by chat/_retrieval.py and evaluation adapters.",
        path,
    )
    b_changes[path] = (before, after)

    path = "src/acne_llm/utils/fuzzy_match.py"
    before = load(snapshot, path)
    after = replace_once(
        before,
        "Two-tier fuzzy match: accept >= auto-include, review <= accept < review = review list.",
        "Return accepted fuzzy matches only; `review` is a lower prefilter threshold.",
        path + " docstring",
    )
    after = replace_once(
        after,
        "review: Include in review list (lower confidence, needs verification)",
        "review: Ignore candidates below this lower threshold; no review list is returned",
        path + " arg",
    )
    after = replace_once(
        after,
        "# Two-tier: accept >= auto-accept, review <= accept < review = review needed",
        "# `review` prefilters weak candidates; the return value keeps only `accept` hits.",
        path + " comment",
    )
    b_changes[path] = (before, after)

    path = "src/acne_llm/schemas/extraction.py"
    before = load(snapshot, path)
    after = replace_once(before, "completeness/intent_router", "intent_router", path)
    b_changes[path] = (before, after)

    path = "src/acne_llm/chat/session/fold.py"
    before = load(snapshot, path)
    after = replace_once(
        before, "cong tat dinh\nDUY NHAT con lai", "mot cong tat dinh\nquan trong",
        path + " module claim",
    )
    after = replace_once(
        after, "cong tat dinh duy nhat con lai", "mot cong tat dinh quan trong",
        path + " inline claim",
    )
    b_changes[path] = (before, after)

    path = "src/acne_llm/utils/logging.py"
    before = load(snapshot, path)
    after = replace_once(
        before, "cong tat dinh: injection, genital, thuoc",
        "cac cong tat dinh: injection, genital, thuoc, session medication safety",
        path,
    )
    b_changes[path] = (before, after)
    b_patch = (
        "# Basket B: comments/docstrings/log wording only. Unapplied proposal.\n"
        "# No runtime branch or data shape is changed.\n"
        + "".join(diff_text(path, before, after) for path, (before, after) in sorted(b_changes.items()))
    )

    c_changes: dict[str, tuple[str, str]] = {}
    path = "src/acne_llm/utils/retrieval_query.py"
    before = load(snapshot, path)
    old_function = '''def _no_accent(text: str) -> str:\n    return "".join(\n        c for c in unicodedata.normalize("NFD", text)\n        if unicodedata.category(c) != "Mn"\n    )\n'''
    new_function = '''def _no_accent(text: str) -> str:\n    stripped = "".join(\n        c for c in unicodedata.normalize("NFD", text)\n        if unicodedata.category(c) != "Mn"\n    )\n    return stripped.replace("đ", "d").replace("Đ", "D")\n'''
    after = replace_once(before, old_function, new_function, path)
    c_changes[path] = (before, after)

    path = "src/acne_llm/chat/routing/intent_router.py"
    before = load(snapshot, path)
    after = replace_once(before, ', "+",\n', ",\n", path + " broad plus token")
    c_changes[path] = (before, after)

    path = "src/acne_llm/chat/routing/semantic_router.py"
    before = load(snapshot, path)
    after = replace_once(
        before,
        "confidence=max(0.0, min(1.0, self.nearest_similarity)),",
        "confidence=max(0.0, min(1.0, self.vote_scores.get(self.primary_intent, 0.0))),",
        path,
    )
    c_changes[path] = (before, after)

    path = "src/acne_llm/rag/sparse.py"
    before = load(snapshot, path)
    build_match = re.search(r"(    def build\(self, chunk_ids: list\[str\], texts: list\[str\]\)[^\n]*:\n)", before)
    if not build_match:
        raise RuntimeError(path + ": build signature not found")
    guard = (
        "        if len(chunk_ids) != len(texts):\n"
        "            raise ValueError(\"chunk_ids and texts must have identical lengths\")\n"
    )
    after = before[:build_match.end()] + guard + before[build_match.end():]
    c_changes[path] = (before, after)

    path = "src/acne_llm/chat/_safety.py"
    before = load(snapshot, path)
    occurrences = before.count(r"[^\n]{0,90}")
    if occurrences < 1:
        raise RuntimeError(path + ": dose window not found")
    after = before.replace(r"[^\n]{0,90}", r"[\s\S]{0,60}")
    c_changes[path] = (before, after)
    c_patch = (
        "# Basket C: behavior changes. Unapplied proposal; test and review separately.\n"
        "# This is a conservative executable subset; measurement-gated items remain only in todo.md.\n"
        + "".join(diff_text(path, before, after) for path, (before, after) in sorted(c_changes.items()))
    )

    (patch_dir / "A-docs.patch").write_text(a_patch, encoding="utf-8", newline="\n")
    (patch_dir / "B-comments.patch").write_text(b_patch, encoding="utf-8", newline="\n")
    (patch_dir / "C-code.patch").write_text(c_patch, encoding="utf-8", newline="\n")
    print("A", len(a_patch), "B", len(b_patch), "C", len(c_patch))


if __name__ == "__main__":
    main()
